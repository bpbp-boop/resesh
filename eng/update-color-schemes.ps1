# Regenerates src/Core/Storage/ColorSchemes/ from the iTerm2-Color-Schemes release pinned in
# eng/color-schemes.json: color-schemes.tsv, the themes resesh ships beside its own, and the
# collection's LICENSE. Both are checked in, so builds need no network. To move to a newer
# release, change "release" and "sha256" in the pin and run this again.
#
# The release's Ghostty files are the source: one per scheme, with the 16 ANSI colors and the
# background, foreground, cursor and selection colors resesh draws with.
$ErrorActionPreference = 'Stop'

$repo = Resolve-Path (Join-Path $PSScriptRoot '..')
$pin = Get-Content (Join-Path $PSScriptRoot 'color-schemes.json') -Raw | ConvertFrom-Json
$out = Join-Path $repo 'src\Core\Storage\ColorSchemes'
$work = Join-Path $repo '.artifacts\color-schemes'
New-Item -ItemType Directory -Force $out, $work | Out-Null

$archive = Join-Path $work $pin.asset
if (-not (Test-Path $archive) -or (Get-FileHash $archive -Algorithm SHA256).Hash.ToLower() -ne $pin.sha256) {
    Invoke-WebRequest "$($pin.repository)/releases/download/$($pin.release)/$($pin.asset)" -OutFile $archive
    if ((Get-FileHash $archive -Algorithm SHA256).Hash.ToLower() -ne $pin.sha256) { throw "$($pin.asset) hash mismatch" }
}
$extracted = Join-Path $work 'extracted'
Remove-Item $extracted -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force $extracted | Out-Null
tar -xzf $archive -C $extracted
if ($LASTEXITCODE -ne 0) { throw "could not extract $($pin.asset)" }

$hex = '^#?([0-9A-Fa-f]{6})$'
$rows = foreach ($file in Get-ChildItem (Join-Path $extracted 'ghostty') -File) {
    $values = @{}
    $palette = @{}
    foreach ($line in Get-Content -LiteralPath $file.FullName) {
        if ($line -match '^\s*palette\s*=\s*(\d+)\s*=\s*(\S+)\s*$') { $palette[[int]$Matches[1]] = $Matches[2] }
        elseif ($line -match '^\s*([a-z-]+)\s*=\s*(\S+)\s*$') { $values[$Matches[1]] = $Matches[2] }
    }
    $keys = 'background', 'foreground', 'cursor-color', 'selection-background', 'selection-foreground'
    $colors = @($keys | ForEach-Object { $values[$_] }) + @(0..15 | ForEach-Object { $palette[$_] })
    $bad = @($colors | Where-Object { $_ -notmatch $hex })
    if ($bad.Count -gt 0 -or $file.Name -match '[\t\r\n]') {
        Write-Warning "Skipping '$($file.Name)': missing or malformed colors"
        continue
    }
    $file.Name + "`t" + (($colors | ForEach-Object { ($_ -replace '^#', '').ToUpperInvariant() }) -join "`t")
}
$rows = $rows | Sort-Object { $_.Split("`t")[0] } -Culture ([cultureinfo]::InvariantCulture)

$header = @(
    "# iTerm2-Color-Schemes $($pin.release) ($($pin.repository)), generated by eng/update-color-schemes.ps1. Do not edit."
    '# name, background, foreground, cursor, selection background, selection foreground, ANSI 0-15 (RRGGBB)'
)
[IO.File]::WriteAllText((Join-Path $out 'color-schemes.tsv'), (($header + $rows) -join "`n") + "`n")
Invoke-WebRequest "https://raw.githubusercontent.com/mbadolato/iTerm2-Color-Schemes/$($pin.release)/LICENSE" `
    -OutFile (Join-Path $out 'iTerm2-Color-Schemes-LICENSE.txt')
Write-Host "Wrote $(@($rows).Count) color schemes to $out"
